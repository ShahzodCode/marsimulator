"""Synthesise every sound effect from scratch (numpy) and encode to Ogg Vorbis with Blender's `aud`.

    blender --background --python source/make_audio.py

All sounds are original, generated by the code below (CC0).  44.1 kHz mono, loudness-normalised to
about -14 LUFS (ITU-R BS.1770 K-weighting, gated), with a -1 dBFS peak ceiling.
"""
import os, sys, json, math
import numpy as np
import aud

HERE = os.path.dirname(os.path.abspath(__file__))
PACK = os.path.dirname(HERE)
BUILD = os.path.join(os.path.dirname(PACK), '_build')
OUT = os.path.join(PACK, 'audio')
SR = 44100
rng = np.random.default_rng(2031)


def t_(dur):
    return np.arange(int(dur * SR)) / SR


def place(buf, sig, at):
    i = int(at * SR)
    n = min(len(sig), len(buf) - i)
    buf[i:i + n] += sig[:n]


def fade(sig, a=0.004, r=0.03):
    n_a, n_r = int(a * SR), int(r * SR)
    sig = sig.copy()
    sig[:n_a] *= np.linspace(0, 1, n_a)
    sig[-n_r:] *= np.linspace(1, 0, n_r) ** 2
    return sig


def sweep(f0, f1, dur, curve=1.0):
    t = t_(dur)
    f = f0 + (f1 - f0) * (t / dur) ** curve
    return np.sin(2 * np.pi * np.cumsum(f) / SR), f


def bell(f, dur, tau=0.35, partials=((1, 1.0), (2, 0.35), (3, 0.15), (4.2, 0.07))):
    t = t_(dur)
    s = sum(a * np.sin(2 * np.pi * f * k * t) * np.exp(-t / (tau / k ** 0.6)) for k, a in partials)
    return fade(s, 0.003, 0.05)


def beep(f, dur=0.09, h2=0.2):
    t = t_(dur)
    return fade(np.sin(2 * np.pi * f * t) + h2 * np.sin(4 * np.pi * f * t), 0.008, 0.03)


def band_noise(n, shape):
    """Noise with an arbitrary magnitude spectrum shape(f); periodic over n samples (so it loops)."""
    f = np.fft.rfftfreq(n, 1 / SR)
    spec = shape(f) * np.exp(2j * np.pi * rng.random(len(f)))
    spec[0] = 0
    x = np.fft.irfft(spec, n)
    return x / np.max(np.abs(x))


def motor(f, amp):
    ph = 2 * np.pi * np.cumsum(f) / SR
    s = sum(np.sin(k * ph) / k ** 1.4 for k in range(1, 9))
    s += 0.25 * np.sin(6.5 * ph) * (0.5 + 0.5 * np.sin(2 * np.pi * 11 * np.arange(len(f)) / SR))
    return s * amp


# ----------------------------------------------------------------------------- the sounds
def ui_click():
    s, _ = sweep(1500, 900, 0.07)
    t = t_(0.07)
    return fade(s * np.exp(-t / 0.012) + 0.3 * rng.standard_normal(len(t)) * np.exp(-t / 0.003), 0.0005, 0.02)


def ui_open_panel():
    d = 0.3
    s, _ = sweep(380, 1150, d, 0.7)
    t = t_(d)
    env = np.sin(np.pi * (t / d) ** 0.6) ** 1.5
    air = band_noise(len(t), lambda f: np.exp(-((f - 2600) / 1500) ** 2))
    return fade((0.7 * s + 0.35 * air) * env, 0.004, 0.05)


def build_place():
    d = 0.42
    buf = np.zeros(int(d * SR))
    s, _ = sweep(150, 58, 0.3, 0.5)
    place(buf, s * np.exp(-t_(0.3) / 0.085), 0)
    t = t_(0.02)
    place(buf, 0.5 * rng.standard_normal(len(t)) * np.exp(-t / 0.004), 0)
    for f, a in ((520, 0.35), (790, 0.2)):
        t = t_(0.2)
        place(buf, a * np.sin(2 * np.pi * f * t) * np.exp(-t / 0.045), 0.005)
    return fade(buf, 0.0005, 0.05)


def build_complete():
    buf = np.zeros(int(1.4 * SR))
    for i, f in enumerate((523.25, 659.25, 783.99, 1046.5)):
        place(buf, bell(f, 1.0, 0.33), i * 0.115)
    return fade(buf, 0.001, 0.12)


def warning():
    buf = np.zeros(int(1.15 * SR))
    for at, f in ((0, 587.33), (0.2, 440.0), (0.58, 587.33), (0.78, 440.0)):
        t = t_(0.3)
        tone = (np.sin(2 * np.pi * f * t) + 0.12 * np.sin(4 * np.pi * f * t)) * np.exp(-t / 0.16)
        place(buf, fade(tone, 0.018, 0.08), at)
    return fade(buf, 0.002, 0.08)


def rover_depart():
    d = 1.6
    t = t_(d)
    buf = np.zeros(len(t))
    place(buf, 0.5 * beep(880), 0.0)
    place(buf, 0.5 * beep(1174.66), 0.12)
    f = 70 + 125 * np.clip((t - 0.25) / 1.1, 0, 1) ** 0.7
    amp = np.clip((t - 0.22) / 0.2, 0, 1) * np.clip((d - t) / 0.75, 0, 1) ** 1.3
    buf += 0.6 * motor(f, amp)
    buf += 0.12 * band_noise(len(t), lambda fr: np.exp(-((fr - 900) / 700) ** 2)) * amp
    return fade(buf, 0.002, 0.1)


def rover_arrive():
    d = 1.5
    t = t_(d)
    buf = np.zeros(len(t))
    f = 60 + 135 * np.clip(1 - t / 1.0, 0, 1) ** 1.2
    amp = np.clip(t / 0.5, 0, 1) ** 1.5 * np.clip((1.02 - t) / 0.25, 0, 1)
    buf += 0.6 * motor(f, amp)
    buf += 0.12 * band_noise(len(t), lambda fr: np.exp(-((fr - 900) / 700) ** 2)) * amp
    place(buf, 0.5 * beep(880), 1.08)
    place(buf, 0.5 * beep(1318.51, 0.16), 1.21)
    return fade(buf, 0.03, 0.08)


def rank_up():
    buf = np.zeros(int(2.3 * SR))
    for i, f in enumerate((523.25, 659.25, 783.99, 1046.5, 1318.51)):
        place(buf, 0.8 * bell(f, 0.7, 0.25), i * 0.095)
    for f, a in ((523.25, 0.7), (659.25, 0.6), (783.99, 0.6), (1046.5, 0.7), (1567.98, 0.3)):
        place(buf, a * bell(f, 1.7, 0.75), 0.56)
    for i in range(9):                                   # sparkle
        f = (2093.0, 2637.0, 3136.0, 3951.0)[i % 4]
        place(buf, 0.12 * bell(f, 0.3, 0.09, ((1, 1.0),)), 0.62 + i * 0.085)
    return fade(buf, 0.001, 0.25)


def ambient_wind_loop():
    d = 30.0
    n = int(d * SR)
    t = np.arange(n) / SR

    def lfo(parts):                                      # whole cycles per loop -> seamless
        return sum(a * np.sin(2 * np.pi * k * t / d + ph) for k, a, ph in parts)

    body = band_noise(n, lambda f: (f / (f + 70)) / (1 + (f / 420) ** 2) ** 0.9)
    hiss = band_noise(n, lambda f: np.exp(-((f - 2400) / 1300) ** 2))
    whistle = band_noise(n, lambda f: np.exp(-((f - 1350) / 110) ** 2) + 0.6 * np.exp(-((f - 1720) / 90) ** 2))
    g1 = 0.6 + lfo(((1, 0.22, 0.3), (3, 0.13, 1.9), (7, 0.07, 4.0), (13, 0.04, 2.2)))
    g2 = np.clip(0.35 + lfo(((2, 0.3, 1.1), (5, 0.2, 5.2), (11, 0.1, 0.4))), 0, None)
    g3 = np.clip(lfo(((1, 0.5, 3.6), (4, 0.4, 0.9), (9, 0.2, 2.5))) - 0.25, 0, None)
    return body * g1 + 0.1 * hiss * g2 + 0.07 * whistle * g3


SOUNDS = [  # id, generator, loop, bitrate
    ('ui_click', ui_click, False, 64000), ('ui_open_panel', ui_open_panel, False, 64000),
    ('build_place', build_place, False, 64000), ('build_complete', build_complete, False, 64000),
    ('warning', warning, False, 64000), ('rover_depart', rover_depart, False, 64000),
    ('rover_arrive', rover_arrive, False, 64000), ('rank_up', rank_up, False, 64000),
    ('ambient_wind_loop', ambient_wind_loop, True, 32000),
]


# ----------------------------------------------------------------------------- loudness (BS.1770)
def k_weight(x):
    n = len(x)
    w = 2 * np.pi * np.fft.rfftfreq(n)
    z1, z2 = np.exp(-1j * w), np.exp(-2j * w)
    A, w0 = 10 ** (4.0 / 40), 2 * np.pi * 1500 / SR
    al = np.sin(w0) / (2 * (1 / np.sqrt(2)))
    c = np.cos(w0)
    b = (A * ((A + 1) + (A - 1) * c + 2 * np.sqrt(A) * al), -2 * A * ((A - 1) + (A + 1) * c), A * ((A + 1) + (A - 1) * c - 2 * np.sqrt(A) * al))
    a = ((A + 1) - (A - 1) * c + 2 * np.sqrt(A) * al, 2 * ((A - 1) - (A + 1) * c), (A + 1) - (A - 1) * c - 2 * np.sqrt(A) * al)
    H = (b[0] + b[1] * z1 + b[2] * z2) / (a[0] + a[1] * z1 + a[2] * z2)
    w0 = 2 * np.pi * 38 / SR
    al, c = np.sin(w0) / (2 * 0.5), np.cos(w0)
    H *= ((1 + c) / 2 - (1 + c) * z1 + (1 + c) / 2 * z2) / ((1 + al) - 2 * c * z1 + (1 - al) * z2)
    return np.fft.irfft(np.fft.rfft(x) * H, n)


def lufs(x):
    y = k_weight(x)
    blk, hop = int(0.4 * SR), int(0.1 * SR)
    if len(y) < blk:
        return -0.691 + 10 * np.log10(np.mean(y ** 2) + 1e-12)
    ms = np.array([np.mean(y[i:i + blk] ** 2) for i in range(0, len(y) - blk + 1, hop)])
    L = -0.691 + 10 * np.log10(ms + 1e-12)
    ms = ms[L > -70]
    rel = -0.691 + 10 * np.log10(np.mean(ms)) - 10
    ms = ms[(-0.691 + 10 * np.log10(ms)) > rel]
    return -0.691 + 10 * np.log10(np.mean(ms))


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(BUILD, exist_ok=True)
    stats = {}
    for name, gen, loop, bitrate in SOUNDS:
        x = np.asarray(gen(), dtype=np.float64)
        x -= np.mean(x)
        # loudness-normalise through a gentle tanh soft limiter (ceiling -1 dBFS); iterate because the
        # limiter itself changes the loudness of peaky sounds.  Gain is capped so nothing gets crushed.
        ceil = 10 ** (-1 / 20)
        peak = np.max(np.abs(x))
        g = 10 ** ((-14.0 - lufs(x)) / 20)
        for _ in range(8):
            g = min(g, 2.2 * ceil / peak)
            y = ceil * np.tanh(x * g / ceil) if np.max(np.abs(x * g)) > 0.7 * ceil else x * g
            g *= 10 ** ((-14.0 - lufs(y)) / 20)
        x = y
        path = os.path.join(OUT, name + '.ogg')
        snd = aud.Sound.buffer(x.astype(np.float32).reshape(-1, 1), SR)
        snd.write(path, rate=SR, channels=aud.CHANNELS_MONO, format=aud.FORMAT_S16,
                  container=aud.CONTAINER_OGG, codec=aud.CODEC_VORBIS, bitrate=bitrate)
        back = np.asarray(aud.Sound(path).data())[:, 0].astype(np.float64)
        st = dict(file='audio/' + name + '.ogg', id=name, kind='sound',
                  duration_s=round(len(back) / SR, 3), loop=loop, bytes=os.path.getsize(path),
                  sample_rate=SR, channels=1, lufs=round(float(lufs(back)), 1),
                  peak_dbfs=round(float(20 * np.log10(np.max(np.abs(back)))), 1),
                  license='CC0-1.0', source='synthesised (source/make_audio.py)')
        if loop:
            st['loop_seam_step'] = round(float(abs(back[0] - back[-1])), 4)
            st['samples_in'] = len(x)
            st['samples_out'] = len(back)
        stats[name] = st
        print('AUDIO', st)
    json.dump(stats, open(os.path.join(BUILD, 'audio_stats.json'), 'w'), indent=1)
